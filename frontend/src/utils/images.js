// Helper function to get optimized image URL
export const getImageUrl = (category, type, size = 'medium') => {
  const sizes = {
    small: { w: 400, h: 300 },
    medium: { w: 800, h: 600 },
    large: { w: 1200, h: 800 },
    hero: { w: 1920, h: 1080 }
  };

  const { w, h } = sizes[size] || sizes.medium;
  const baseUrl = images[category]?.[type] || images.services.spa;

  // Add size parameters if not already present
  if (baseUrl.includes('?')) {
    return `${baseUrl}&w=${w}&h=${h}&fit=crop&q=80`;
  }
  return `${baseUrl}?w=${w}&h=${h}&fit=crop&q=80`;
};
